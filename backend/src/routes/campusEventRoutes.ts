import { Router } from 'express';
import { authorize, protect } from '../middleware/auth';
import { browseCampusEvents, cancelStudentRegistration, createEvent, eventAction, eventRoster, getCampusEvent, getOwnedEvent, getRegistration, markAttendance, organizerDecision, organizerHistory, organizerQueue, ownedEventHistory, ownedEvents, ownOrganizer, registerStudent, registrationHistory, studentRegistrations } from '../controllers/campusEventController';
const router = Router();
router.use((_req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
router.get('/', browseCampusEvents);
const account = Router(); account.use(protect); account.use((req, res, next) => { if (req.user?.requiresEmailVerification && !req.user.emailVerifiedAt) { res.status(403).json({ success: false, message: 'Verify your email before accessing campus event activity.' }); return; } next(); });
account.get('/admin', authorize('admin'), ownedEvents(true));
account.get('/admin/organizers', authorize('admin'), organizerQueue);
account.put('/admin/organizers/:id', authorize('admin'), organizerDecision);
account.get('/admin/organizers/:id/history', authorize('admin'), organizerHistory);
account.post('/admin/:id/cancel', authorize('admin'), eventAction('cancel', true));
account.get('/organizer', authorize('student', 'provider'), ownOrganizer);
account.get('/mine', authorize('student', 'provider'), ownedEvents());
account.get('/mine/:id', authorize('student', 'provider'), getOwnedEvent);
account.get('/mine/:id/history', authorize('student', 'provider'), ownedEventHistory);
account.get('/registrations/mine', authorize('student'), studentRegistrations);
account.get('/registrations/:id', authorize('student', 'provider'), getRegistration);
account.get('/registrations/:id/history', authorize('student', 'provider'), registrationHistory);
account.post('/registrations/:id/cancel', authorize('student'), cancelStudentRegistration);
account.patch('/registrations/:id/attendance', authorize('student', 'provider'), markAttendance);
account.post('/', authorize('student', 'provider'), createEvent);
account.patch('/:id', authorize('student', 'provider'), eventAction('edit'));
account.post('/:id/publish', authorize('student', 'provider'), eventAction('publish'));
account.post('/:id/cancel', authorize('student', 'provider'), eventAction('cancel'));
account.post('/:id/complete', authorize('student', 'provider'), eventAction('complete'));
account.post('/:id/registrations', authorize('student'), registerStudent);
account.get('/:id/registrations', authorize('student', 'provider'), eventRoster);
router.get('/:id', (req, res, next) => { if (['admin', 'organizer', 'mine', 'registrations'].includes(String(req.params.id))) { next(); return; } void getCampusEvent(req, res); });
router.use(account);
export default router;
